"""CLI for MLX LADA restore fixtures."""

from __future__ import annotations

import argparse
import glob
from pathlib import Path

from experiments.mlx_dcnv2.bundle import load_lada_mlx_bundle
from experiments.mlx_dcnv2.native_detection import detect_video_to_mask_dir
from experiments.mlx_dcnv2.restore_fixture import (
    restore_image_sequence_with_masks,
    restore_video_with_mask_windows,
    restore_video_with_masks,
)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser()
    parser.add_argument("--manifest", required=True, help="Exported LADA MLX manifest JSON")
    masks = parser.add_mutually_exclusive_group(required=True)
    masks.add_argument("--mask-glob", help="Glob for grayscale mask frames")
    masks.add_argument("--native-detection-model", help="LADA native YOLO .pt detection model used to generate masks")
    parser.add_argument("--generated-mask-dir", help="Directory for masks generated by --native-detection-model")
    parser.add_argument("--native-detection-device", default="cpu")
    parser.add_argument("--native-detection-fp16", action="store_true")
    parser.add_argument("--native-detection-conf", type=float, default=0.15)
    parser.add_argument("--native-detection-batch-size", type=int, default=4)
    parser.add_argument("--detect-face-mosaics", action="store_true")
    parser.add_argument("--expansion-ratio", type=float, default=0.0)
    parser.add_argument("--align-multiple", type=int, default=32)
    parser.add_argument("--max-restore-roi-area", type=int, help="Split restore windows when union ROI area exceeds this")
    parser.add_argument("--print-window-timing", action="store_true")
    parser.add_argument("--video-window-size", type=int, default=0, help="Stream video restore in N-frame windows")
    parser.add_argument("--video-window-overlap", type=int, default=4, help="Context frames carried between streamed windows")
    parser.add_argument("--copy-audio", action="store_true", help="Mux optional source audio into the restored video")
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--frame-glob", help="Glob for input image frames")
    source.add_argument("--video-input", help="Input video path")
    output = parser.add_mutually_exclusive_group(required=True)
    output.add_argument("--output-dir", help="Output image directory")
    output.add_argument("--video-output", help="Output video path")
    return parser


def main() -> None:
    parser = build_parser()
    args = parser.parse_args()

    bundle = load_lada_mlx_bundle(args.manifest)
    mask_paths = resolve_mask_paths(args)

    if args.frame_glob:
        if not args.output_dir:
            raise SystemExit("--output-dir is required with --frame-glob")
        output_paths = restore_image_sequence_with_masks(
            _glob_sorted(args.frame_glob),
            mask_paths,
            args.output_dir,
            bundle=bundle,
            expansion_ratio=args.expansion_ratio,
            align_multiple=args.align_multiple,
        )
        print(f"wrote {len(output_paths)} frames to {Path(args.output_dir)}")
        return

    if not args.video_output:
        raise SystemExit("--video-output is required with --video-input")
    if args.video_window_size > 0:
        output_path = restore_video_with_mask_windows(
            args.video_input,
            mask_paths,
            args.video_output,
            bundle=bundle,
            window_size=args.video_window_size,
            overlap=args.video_window_overlap,
            expansion_ratio=args.expansion_ratio,
            align_multiple=args.align_multiple,
            progress_callback=lambda count: print(f"restored frames: {count}", flush=True),
            timing_callback=_print_window_timing if args.print_window_timing else None,
            copy_audio=args.copy_audio,
            max_restore_roi_area=args.max_restore_roi_area,
        )
        print(f"wrote streamed video to {output_path}")
        return

    output_path = restore_video_with_masks(
        args.video_input,
        mask_paths,
        args.video_output,
        bundle=bundle,
        expansion_ratio=args.expansion_ratio,
        align_multiple=args.align_multiple,
        copy_audio=args.copy_audio,
    )
    print(f"wrote video to {output_path}")


def _glob_sorted(pattern: str) -> list[Path]:
    paths = [Path(path) for path in glob.glob(pattern)]
    if not paths:
        raise SystemExit(f"no paths matched: {pattern}")
    return sorted(paths)


def resolve_mask_paths(
    args: argparse.Namespace,
    *,
    detect_video_to_mask_dir=detect_video_to_mask_dir,
) -> list[Path]:
    if args.mask_glob:
        return _glob_sorted(args.mask_glob)
    if not args.video_input:
        raise SystemExit("--video-input is required with --native-detection-model")
    generated_mask_dir = Path(args.generated_mask_dir) if args.generated_mask_dir else Path(args.video_input).with_suffix(".native_masks")
    return detect_video_to_mask_dir(
        args.video_input,
        generated_mask_dir,
        model_path=args.native_detection_model,
        device=args.native_detection_device,
        fp16=args.native_detection_fp16,
        conf=args.native_detection_conf,
        detect_face_mosaics=args.detect_face_mosaics,
        batch_size=args.native_detection_batch_size,
    )


def _print_window_timing(timing: dict[str, float | int]) -> None:
    print(
        "window timing: "
        f"start={timing['window_start']} "
        f"frames={timing['window_frames']} "
        f"restore={timing['restore_seconds']:.3f}s "
        f"fps={timing['effective_fps']:.3f}",
        flush=True,
    )


if __name__ == "__main__":
    main()
